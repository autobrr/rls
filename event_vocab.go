package rls

// The vocabulary of Event: the competitions a sports name starts with, the
// shows and numbered series inside them, and the words for a round, a session
// and a part of a card. A spelling is the words of the name in lower case with
// one space between them, so 'Formula.1', 'Formula_1' and 'Formula 1' are all
// "formula 1". Spellings of one row are separated by "|". In the words for a
// round "#" stands for a number, written in digits or as a word ("r#" is 'R09',
// "#rd round" is '3rd Round', "day #" is 'Day 2' and 'Day Two').
//
// In a sport of single athletes the competition is the sport and the
// tournament a name inside it, however the name is written: 'Wimbledon.2023',
// 'Tennis.Wimbledon.2023' and 'ATP.Wimbledon.2023' are Tennis and Wimbledon.
// In a team sport the league is the competition, and the word for the sport in
// front of it is skipped: 'Fussball.Bundesliga' is Bundesliga.
//
// The lists were written for this package from release names and from general
// knowledge of the leagues. They are not taken from another project.

// Flags of a competition or of a name inside one.
const (
	// evWeak marks a spelling that is the word for a sport ('Tennis',
	// 'Boxing'), short ('F1', 'ATP') or also the start of other titles
	// ('Wimbledon', 'World Cup'). A year and more text after it are not
	// enough to make the name an event.
	evWeak = 1 << iota
	// evNumbered marks events that are numbered ('UFC 300'), where the number
	// follows directly.
	evNumbered
	// evRoman marks events numbered in roman numerals ('Super Bowl LVIII').
	evRoman
	// evMotor marks motorsport, where a weekend has sessions.
	evMotor
	// evOnce marks an event held once a year ('Paris-Roubaix', 'Daytona
	// 500'), for which the year is all a name needs.
	evOnce
)

